/**
 * Detects whether a prompt or response refers to Acts, Sections, or Judgments
 */
export function detectLegalTopics(text) {
  if (!text) return { hasActs: false, hasJudgments: false, matchedActs: [], searchQuery: "" };
  const lower = text.toLowerCase();

  const matchedActs = BARE_ACTS_CATALOG.filter((act) => {
    return act.keywords.some((kw) => {
      const escaped = kw.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");
      const rgx = new RegExp(`(^|\\W)${escaped}(\\W|$)`, "i");
      return rgx.test(text);
    });
  });

  const judgmentKeywords = [
    "judgement", "judgment", "ruling", "precedent", "case law", "supreme court",
    "high court", "tribunal", "itat", "nclat", "versus", "citation",
    "division bench", "full bench", "quash"
  ];
  const hasJudgments = judgmentKeywords.some((jk) => {
    const escaped = jk.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&");
    const rgx = new RegExp(`(^|\\W)${escaped}(\\W|$)`, "i");
    return rgx.test(text);
  }) || /\bvs\.?\b/i.test(text);

  // Extract candidate search terms for case law
  let searchQuery = "";
  if (hasJudgments || matchedActs.length > 0) {
    const caseMatch = text.match(/([A-Z][a-zA-Z0-9\s.]+)\s+(?:v\.|vs|versus)\s+([A-Z][a-zA-Z0-9\s.]+)/i);
    if (caseMatch) {
      searchQuery = caseMatch[0].trim();
    } else if (matchedActs.length > 0) {
      searchQuery = `${matchedActs[0].name} judgments`;
    } else {
      searchQuery = "Supreme Court of India judgments";
    }
  }

  return {
    hasActs: matchedActs.length > 0,
    hasJudgments,
    matchedActs,
    searchQuery,
  };
}

/**
 * Generates a clean, authoritative markdown block containing verified Bare Act and Judgment links
 */
export function buildLegalLinksMarkdown(text, userPrompt = "") {
  const combined = `${userPrompt} ${text}`;
  const detection = detectLegalTopics(combined);

  if (!detection.hasActs && !detection.hasJudgments) {
    return "";
  }

  // If the text already has bare act or judgment links, avoid duplicating
  if (text.includes("indiacode.nic.in") || text.includes("indiankanoon.org")) {
    return "";
  }

  const sections = [];
  sections.push(`\n\n---\n### 📚 Official Bare Act & Public Judgement Copy Links\n`);

  if (detection.matchedActs.length > 0) {
    sections.push(`**Official Bare Acts (Government of India):**\n`);
    const actsToShow = detection.matchedActs.slice(0, 2);
    for (const act of actsToShow) {
      sections.push(`- 🏛️ **[${act.name} — Official Bare Act (India Code)](${act.bareActUrl})**  \n  *${act.description}* — [Department Portal ↗](${act.departmentUrl})`);
    }
  }

  sections.push(`\n**Public Judgement Copies & Judicial Records:**\n`);
  const searchPhrase = detection.searchQuery || "Supreme Court of India";
  const kanoonLink = PUBLIC_CASE_LAW_PORTALS.indianKanoon.searchUrl(searchPhrase);

  sections.push(`- ⚖️ **[Search Free Public Judgement Copy on Indian Kanoon](${kanoonLink})**  \n  *Instant access to full-text Supreme Court, High Court & ITAT orders matching this query.*`);
  sections.push(`- 📜 **[Supreme Court Official Digital Reports (DigiSCR / e-SCR)](${PUBLIC_CASE_LAW_PORTALS.digiSCR.url})**  \n  *Official digital judgements published by the Supreme Court of India.*`);

  if (combined.toLowerCase().includes("itat") || combined.toLowerCase().includes("income tax")) {
    sections.push(`- 📊 **[Income Tax Appellate Tribunal (ITAT) Official Orders Portal](${PUBLIC_CASE_LAW_PORTALS.itat.url})**`);
  }
  if (combined.toLowerCase().includes("nclat") || combined.toLowerCase().includes("ibc") || combined.toLowerCase().includes("companies act")) {
    sections.push(`- 🏢 **[NCLAT Official Appellate Judgements Portal](${PUBLIC_CASE_LAW_PORTALS.nclat.url})**`);
  }

  return sections.join("\n");
}
